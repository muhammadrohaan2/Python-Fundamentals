# Indexing 
text = "Python"

#Extract the first character 
print(text[0]) 
print(text[-6]) 

#Extract the last character
print(text[5])
print(text[-1]) 

#Extract h
print(text[3])
print(text[-3]) 

# Slicing
date = "2026-11-5"

#Extract the year
print(date[0:4])
print(date[:4])

#Extract the month 
print(date [5:7])

#Extract the day
print(date[8:9])
print(date[8:])

